results = {}
with sync_playwright() as p:
    b = p.chromium.launch(headless=True)
    pg = b.new_page()
    for aid, pub_date, title in ANNOUNCEMENTS:
        url = f'https://www.csindex.com.cn/#/about/newsDetail?id={aid}'
        try:
            pg.goto(url, timeout=60000, wait_until='domcontentloaded')
            pg.wait_for_timeout(2500)
            txt = pg.inner_text('body')
            results[aid] = {'publish_date': pub_date, 'title': title, 'text': txt}
            print(f'{pub_date} id={aid} 正文长度={len(txt)} 抓取OK', flush=True)
        except Exception as e:
            print(f'{pub_date} id={aid} 失败: {e}', flush=True)
            results[aid] = {'publish_date': pub_date, 'title': title, 'text': ''}
    b.close()

with open('scratch/csindex_announcements_2010s.json', 'w', encoding='utf-8') as f:
    json.dump(results, f, ensure_ascii=False, indent=1)
